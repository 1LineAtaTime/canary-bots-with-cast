#!/usr/bin/env python3
"""Generate the GM town-tour scenario from the server's `towns` table (P5 #160 V10).

    python tools/bottest/gen_town_tour.py --db canary_1525_port [--db-host <db-host>] [--db-port 3306]
                                          [--dwell 50] [--out tools/bottest/scenarios/p5_lxc_gm_town_tour.steps]

The town list is read from the DB, never hard-coded: every row of `towns`, boat-only and island towns
included. Per stop the scenario marks the audit stream, resets the engine perf counters, teleports the GM
there with /town <id>, dwells (default 5 s, enough to trigger the wakes; user 2026-11-20), then reads perfstat and the client view.
town_tour_report.py turns the run dir into the per-town table. Credentials: the DB user/password come
from .claude/secrets.local (BOTPERF_SECRETS overrides the path); the GM login password is a runner
--var GMPW, never written into the scenario.
"""
from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO))
from tools.botperf.driver import BotCommandDriver, DbConfig  # noqa: E402


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--db", required=True)
    ap.add_argument("--db-host")
    ap.add_argument("--db-port")
    ap.add_argument("--dwell", type=int, default=5)
    ap.add_argument("--settle", type=int, default=60, help="tail at the last town so the awake numbers have something to read")
    ap.add_argument("--out", default=str(REPO / "tools/bottest/scenarios/p5_lxc_gm_town_tour.steps"))
    a = ap.parse_args()
    os.environ["BOTPERF_DB"] = a.db
    if a.db_host:
        os.environ["BOTPERF_DB_HOST"] = a.db_host
    if a.db_port:
        os.environ["BOTPERF_DB_PORT"] = a.db_port
    db = DbConfig.from_secrets()
    rows = BotCommandDriver(db)._sql("SELECT id, name, posx, posy, posz FROM towns ORDER BY id")
    towns = [(int(r[0]), r[1], r[2], r[3], r[4]) for r in rows if r and r[0].isdigit()]
    if not towns:
        print("no towns read", file=sys.stderr)
        return 1
    L = [
        "# SCENARIO: p5_lxc_gm_town_tour   SEED: 0   CAMERAS: none   BOTCFG: auto",
        f"# GENERATED by tools/bottest/gen_town_tour.py from `{a.db}`.towns ({len(towns)} towns) - regenerate, do not hand-edit.",
        "# P5 (#160) V10: a GM (monsters/PKers cannot hurt it) visits EVERY town temple, dwells for nearby bots to wake,",
        "# and per stop the engine perfstat window + census + journal + host samples are recorded",
        "# (town_tour_report.py). Run: runner.py <this> --profile <lxc profile> --var GMCHAR=GOD --var GMACCT=@god --var GMPW=<pw>",
        "@srv audit kinds census,cmd",
        "@srv audit on expect=\"enabled=on\"",
        "@p1 login char=\"$GMCHAR\" acct=$GMACCT pw=$GMPW",
    ]
    for tid, name, x, y, z in towns:
        L += [
            f"@srv audit mark \"town {tid} {name} ({x},{y},{z})\"",
            "@srv cmd _global perfreset",
            f"@p1 say /town {tid}",
            f"@p1 hold {a.dwell}",
            "@srv cmd _global perfstat",
            "@p1 view recent=60000",
        ]
    L += ["@srv audit mark \"settle tail\"", "@srv cmd _global perfreset", f"@p1 hold {a.settle}", "@srv cmd _global perfstat",
          "@p1 view recent=60000", "@srv audit mark \"tour end\"", "@p1 logout", "@srv audit off"]
    Path(a.out).write_text("\n".join(L) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {a.out}: {len(towns)} towns, dwell {a.dwell}s (~{len(towns) * (a.dwell + 8) // 60} min)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
